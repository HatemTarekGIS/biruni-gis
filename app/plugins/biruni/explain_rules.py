"""Known error messages of QGIS, GDAL/OGR, PROJ, GEOS, Processing, GRASS and
Python, with a plain explanation and what to do. Used by explain.py.

Each rule: id, regular expressions (English text, and the Arabic text where
QGIS translates the message), title, cause, fix, an optional action and sample
messages for the tests. Rules are tried in order: specific ones first.

Actions: a Biruni command id (commands.CATALOG), a Processing algorithm id, or
"folder" (open the folder of the file named in the message).
"""


def tr(text):
    """Marks a text for scripts/extract_strings.py; it is translated when shown."""
    return text


def rule(rid, patterns, title, cause, fix, action=None, samples=()):
    return {"id": rid, "patterns": patterns, "title": title, "cause": cause, "fix": fix, "action": action,
            "samples": samples}


